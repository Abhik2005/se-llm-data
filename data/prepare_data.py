"""
data/prepare_data.py — Download, Tokenize, and Save Pre-Training Data.

Builds train.bin and val.bin — the binary token files read by the training loop.
Run this after tokenizer/train_tokenizer.py completes.

Token target: 7B tokens (Chinchilla-optimal for 350M model: 20 × 350M = 7B)

Data mix (70% code | 20% English | 10% SE conversations):
  CODE (70%):
    - bigcode/the-stack         ← actual code files, 16 languages (needs HF token)
    - ise-uiuc/Magicoder-OSS-75K     ← SE problems + solutions
    - theblackcat102/evol-codealpaca  ← complex coding tasks
    - m-a-p/CodeFeedback              ← code review + bug fixing

  ENGLISH (20%):
    - HuggingFaceFW/fineweb-edu      ← educational web text, planning/explaining

  SE CONVERSATIONS (10%):
    - teknium/OpenHermes-2.5         ← multi-turn coding + general discussions

HF Token required for the-stack-smol:
  1. huggingface.co/settings/tokens → create Read token
  2. Accept terms: huggingface.co/datasets/bigcode/the-stack
  3. Add to .env:  HF_TOKEN=hf_xxxxxxxxxxxx
     OR set env:   $env:HF_TOKEN = "hf_xxxxxxxxxxxx"

Output:
    data/processed/train.bin   (uint16 flat token IDs, ~14 GB)
    data/processed/val.bin     (~200 MB)

Usage:
    python data/prepare_data.py
    python data/prepare_data.py --max-tokens 1000000000   # 1B quick test
"""

