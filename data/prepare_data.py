# ── Tokenization + binary writing ──────────────────────────────────────────────

def tokenize_and_write(
    text_iterator: Iterator[str],
    tokenizer,
    output_path: str,
    target_tokens: int,
    eos_token_id: int = 1,
    report_every: int = 100_000_000,
    start_tokens: int = 0,
) -> int:
    """
    Tokenize a stream of text and write as flat uint16 binary file.
    EOS token is appended between every document.
    Supports resuming from existing binary file if start_tokens > 0.
    Returns total tokens written / in file.
    """
    os.makedirs(os.path.dirname(output_path), exist_ok=True)

    mode = "ab" if (start_tokens > 0 and os.path.exists(output_path)) else "wb"

    total_tokens = start_tokens
    total_docs   = 0
    buffer       = []
    FLUSH_SIZE   = 100_000
    last_report  = start_tokens
    t_start      = time.time()

    # Fast skip if resuming
    chars_to_skip = start_tokens * 4  # Average ~4 chars per token
    skipped_chars = 0
    if start_tokens > 0:
        print(f"Resuming {output_path}: fast-skipping ~{chars_to_skip/1e9:.2f}B chars (~{start_tokens/1e9:.3f}B tokens)...")

    print(f"\nWriting ({mode}) → {output_path}")
    print(f"Target:    {target_tokens / 1e9:.2f}B tokens (starting at {total_tokens / 1e9:.3f}B)\n")

    with open(output_path, mode) as f:
        for text in text_iterator:
            if total_tokens >= target_tokens:
                break

            if skipped_chars < chars_to_skip:
                skipped_chars += len(text)
                if skipped_chars % 2_000_000_000 < len(text):
                    print(f"  Fast-forwarding stream... {skipped_chars/1e9:.2f}B / {chars_to_skip/1e9:.2f}B chars skipped", flush=True)
                continue

            try:
                ids = tokenizer.encode(text).ids
            except Exception:
                continue
            if not ids:
                continue

            ids.append(eos_token_id)
            buffer.extend(ids)
            total_tokens += len(ids)
            total_docs   += 1

            if len(buffer) >= FLUSH_SIZE:
                np.array(buffer[:FLUSH_SIZE], dtype=np.uint16).tofile(f)
                buffer = buffer[FLUSH_SIZE:]

            if total_tokens - last_report >= report_every:
                elapsed = time.time() - t_start
                tok_sec = (total_tokens - start_tokens) / max(elapsed, 1)
                pct     = 100 * total_tokens / target_tokens
                rem_tok = target_tokens - total_tokens
                eta_h   = rem_tok / max(tok_sec, 1) / 3600 if tok_sec > 0 else 0
                print(
                    f"  {total_tokens/1e9:.3f}B / {target_tokens/1e9:.1f}B "
                    f"({pct:.1f}%) | {tok_sec/1000:.1f}K tok/sec | "
                    f"ETA {eta_h:.1f}h | docs: {total_docs:,}"
                )
                last_report = total_tokens

        if buffer:
            np.array(buffer, dtype=np.uint16).tofile(f)

    size_gb = os.path.getsize(output_path) / 1e9
    elapsed = time.time() - t_start
    print(f"\n  Done: {total_tokens:,} tokens | {size_gb:.2f} GB | {elapsed/3600:.1f}h")
    return total_tokens


# ── Main ───────────────────────────────────────────────────────────────────────

def prepare_data(max_train_tokens: int, output_dir: str) -> None:
    """Run the full data preparation pipeline."""
    has_token = bool(os.environ.get("HF_TOKEN"))

    print(f"\n{'='*65}")
    print(f"  SE-LLM-350M Data Preparation Pipeline")
    print(f"  Train target: {max_train_tokens / 1e9:.1f}B tokens  "
          f"(Chinchilla-optimal for 350M)")
    print(f"  Val target:   {TARGET_VAL_TOKENS / 1e6:.0f}M tokens")
    print(f"  Mix:          70% code | 20% English | 10% SE conversations")
    print(f"  HF Token:     {'✅ set — gated datasets unlocked' if has_token else '❌ not set — the-stack-smol will be skipped'}")
    print(f"  Output dir:   {output_dir}/")
    print(f"{'='*65}\n")

    # ── Load tokenizer ────────────────────────────────────────────
    tok_path = "tokenizer/tokenizer.json"
    if not os.path.exists(tok_path):
        raise FileNotFoundError(
            f"Tokenizer not found: {tok_path}\n"
            f"Run first: python tokenizer/train_tokenizer.py"
        )
    from tokenizers import Tokenizer
    tokenizer    = Tokenizer.from_file(tok_path)
    eos_token_id = tokenizer.token_to_id("<|endoftext|>") or 1
    print(f"Tokenizer: vocab={tokenizer.get_vocab_size():,} | EOS={eos_token_id}\n")

    total_chars    = max_train_tokens * 4   # ~4 chars per token
    code_budget    = int(total_chars * CODE_RATIO)
    english_budget = int(total_chars * ENGLISH_RATIO)
    seconv_budget  = int(total_chars * SECONV_RATIO)
    seknow_budget  = int(total_chars * SEKNOW_RATIO)

    # Character budgets scaled to guarantee reaching full 7.0B tokens (~35B chars)
    stack_per_lang  = 600_000_000       # 600M chars/lang × 38 languages ≈ 22.8B chars (~5.7B tokens)
    instruct_budget = 1_000_000_000     # 1.0B chars per instruction dataset
    english_budget  = 12_000_000_000    # 12.0B chars (~3.0B tokens) from FineWeb-Edu
    seconv_budget   = 5_000_000_000     # 5.0B chars (~1.25B tokens) from Q&A / Conversations

    # ── TRAINING DATA ─────────────────────────────────────────────
    train_path = os.path.join(output_dir, "train.bin")
    start_train_tokens = 0
    if os.path.exists(train_path):
        size = os.path.getsize(train_path)
        if size % 2 != 0:
            size -= 1
            with open(train_path, "r+b") as f:
                f.truncate(size)
        existing_tokens = size // 2
        if existing_tokens >= max_train_tokens:
            print(f"train.bin complete ({size/1e9:.2f} GB, {existing_tokens/1e9:.3f}B tokens) — skipping.\n")
            start_train_tokens = existing_tokens
        else:
            print(f"train.bin partial ({size/1e9:.2f} GB, {existing_tokens/1e9:.3f}B tokens) — RESUMING to {max_train_tokens/1e9:.1f}B tokens...\n")
            start_train_tokens = existing_tokens

    if start_train_tokens < max_train_tokens:
        print("--- Building / Resuming TRAIN set ---")
        print(f"  Target:          {max_train_tokens/1e9:.1f}B tokens")
        print(f"  Code budget:     {stack_per_lang*len(STACK_LANGUAGES)/1e9:.1f}B chars (Stack)")
        print(f"  English budget:  {english_budget/1e9:.1f}B chars (FineWeb-Edu)\n")

        def all_train_data():
            # ── CODE (70%) ────────────────────────────────────────
            print("\n── CODE ─────────────────────────────────────────────────")
            yield from stream_the_stack(stack_per_lang)
            yield from stream_magicoder(instruct_budget)
            yield from stream_evol_instruct(instruct_budget)
            yield from stream_codefeedback(instruct_budget)
            # ── ENGLISH & SE KNOWLEDGE (30%) ──────────────────────
            print("\n── ENGLISH & SE KNOWLEDGE ──────────────────────────────")
            yield from stream_fineweb_edu(english_budget)
            yield from stream_stack_exchange(seconv_budget)
            yield from stream_openhermes(seconv_budget)
            # ── FILL GAP (Guarantees reaching 7.0B tokens) ────────
            print("\n── FILLING REMAINING GAP TO 7.0B TOKENS ────────────────")
            yield from stream_fineweb_edu(20_000_000_000)

        train_tokens = tokenize_and_write(
            all_train_data(), tokenizer, train_path,
            target_tokens=max_train_tokens, eos_token_id=eos_token_id,
            start_tokens=start_train_tokens,
        )
        print(f"\nTRAIN: {train_tokens/1e9:.3f}B tokens → {train_path}")

    # ── VALIDATION DATA ───────────────────────────────────────────
    val_path = os.path.join(output_dir, "val.bin")
    start_val_tokens = 0
    if os.path.exists(val_path):
        size = os.path.getsize(val_path)
        if size % 2 != 0:
            size -= 1
            with open(val_path, "r+b") as f:
                f.truncate(size)
        existing_tokens = size // 2
        if existing_tokens >= TARGET_VAL_TOKENS:
            print(f"val.bin complete ({size/1e6:.1f} MB, {existing_tokens/1e6:.1f}M tokens) — skipping.\n")
            start_val_tokens = existing_tokens
        else:
            print(f"val.bin partial ({size/1e6:.1f} MB, {existing_tokens/1e6:.1f}M tokens) — RESUMING...\n")
            start_val_tokens = existing_tokens

    if start_val_tokens < TARGET_VAL_TOKENS:
        print("\n--- Building / Resuming VAL set ---")

        def val_data():
            yield from stream_magicoder(TARGET_VAL_TOKENS * 4 // 2)
            yield from stream_fineweb_edu(TARGET_VAL_TOKENS * 4 // 2)

        val_tokens = tokenize_and_write(
            val_data(), tokenizer, val_path,
            target_tokens=TARGET_VAL_TOKENS, eos_token_id=eos_token_id,
            start_tokens=start_val_tokens,
        )
        print(f"VAL: {val_tokens/1e6:.1f}M tokens → {val_path}")

    # ── Summary ───────────────────────────────────────────────────
    print(f"\n{'='*65}")
    print(f"  Data Preparation COMPLETE")
    for fname in ["train.bin", "val.bin"]:
        fpath = os.path.join(output_dir, fname)
        if os.path.exists(fpath):
            n_tokens = os.path.getsize(fpath) // 2
            size_gb  = os.path.getsize(fpath) / 1e9
            print(f"  {fname:<12} {n_tokens/1e9:.3f}B tokens | {size_gb:.2f} GB")
    print(f"\n  Upload to Kaggle:")
    print(f"    1. {output_dir}/train.bin  (~14 GB)")
    print(f"    2. {output_dir}/val.bin")
    print(f"    3. tokenizer/tokenizer.json")
    print(f"{'='*65}\n")


