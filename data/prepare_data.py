# ── Quality filter ─────────────────────────────────────────────────────────────

def is_quality_code(content: str) -> bool:
    """Return True if the code passes basic quality checks."""
    if not content:
        return False
    length = len(content)
    if length < 100 or length > 500_000:
        return False
    lines = content.split("\n")
    if lines and length / len(lines) > 400:
        return False   # Minified
    ascii_ratio = sum(1 for c in content if ord(c) < 128) / length
    if ascii_ratio < 0.80:
        return False   # Binary / non-code
    first_500 = content[:500].lower()
    for marker in ["auto-generated", "do not edit", "generated by", "this file is generated"]:
        if marker in first_500:
            return False
    return True


# ── Data streaming ─────────────────────────────────────────────────────────────

def stream_the_stack(char_budget_per_lang: int) -> Iterator[str]:
    """
    Stream actual code files from bigcode/the-stack (full).
    Best quality — filtered, deduplicated, permissive licenses only.
    Requires HF_TOKEN + accepted terms: huggingface.co/datasets/bigcode/the-stack
    """
    from datasets import load_dataset
    hf_token = os.environ.get("HF_TOKEN")
    if not hf_token:
        print("  [the-stack] No HF_TOKEN set — skipping gated dataset")
        return

    print(f"  [the-stack] Streaming {len(STACK_LANGUAGES)} languages...", flush=True)
    for lang in STACK_LANGUAGES:
        lang_chars = 0
        try:
            ds = load_dataset(
                "bigcode/the-stack",
                data_dir=f"data/{lang}",
                split="train",
                streaming=True,
                token=hf_token,
            )
            for sample in ds:
                if lang_chars >= char_budget_per_lang:
                    break
                content = sample.get("content", "") or ""
                if not is_quality_code(content):
                    continue
                yield content
                lang_chars += len(content)
            print(f"    → {lang}: {lang_chars / 1e9:.2f}B chars")
        except Exception as e:
            print(f"    Warning {lang}: {e}")


